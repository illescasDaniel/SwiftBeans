import Testing
@testable import SwiftBeansGeneratorCore

@Suite("Generator — SPEC Generator rules → Imports")
struct GeneratorImportTests {
	@Test
	func `Given imports of every kind When generated Then each module is imported once with its attributes and conditions`() {
		let result = generateWithContext(
			appFile("/App/A.swift", """
				import struct Foundation.URL
				@preconcurrency import Legacy
				import Swift
				import SwiftUI
				"""),
			appFile("/App/B.swift", """
				#if canImport(UIKit)
				import UIKit
				#elseif canImport(AppKit)
				import AppKit
				#else
				import Headless
				#endif
				@testable import Legacy
				""")
		)
		expectOutput(result, contains: [
			"@preconcurrency @testable import Legacy\n",
			"import SwiftUI\n",
			"#if canImport(UIKit)\nimport UIKit\n#endif",
			"#if !(canImport(UIKit)) && (canImport(AppKit))\nimport AppKit\n#endif",
			"#if !(canImport(UIKit)) && !(canImport(AppKit))\nimport Headless\n#endif",
		])
		expectOutput(result, excludes: ["import Swift\n", "import Foundation.URL", "import struct"])
	}

	@Test
	func `Given plain imports When generated Then the header lists Foundation SwiftBeans then sorted modules`() throws {
		let result = generateWithContext(
			appFile("/App/A.swift", "import Zeta\nimport SwiftBeans\n"),
			appFile("/App/B.swift", "import Alpha\nimport Foundation\nimport Zeta\n")
		)
		let output = try #require(result.output)
		#expect(output.hasPrefix("""
			// Generated by SwiftBeans — do not edit.
			import Foundation
			import SwiftBeans
			import Alpha
			import Zeta

			"""), "\(output)")
	}

	@Test
	func `Given a module imported conditionally and unconditionally When generated Then only the unconditional import is kept`() {
		let result = generateWithContext(
			appFile("/App/A.swift", "import UIKit\n"),
			appFile("/App/B.swift", "#if canImport(UIKit)\nimport UIKit\n#endif\n")
		)
		expectOutput(result, contains: ["import UIKit\n"])
		expectOutput(result, excludes: ["#if canImport(UIKit)"])
	}

	@Test
	func `Given nested if-config imports When generated Then the conditions are combined`() {
		let result = generateWithContext(appFile("/App/A.swift", """
			#if os(iOS)
			#if canImport(ActivityKit)
			import ActivityKit
			#endif
			#endif
			"""))
		expectOutput(result, contains: ["#if (os(iOS)) && (canImport(ActivityKit))\nimport ActivityKit\n#endif"])
	}

	@Test
	func `Given UI and test modules When generated Then they are not skipped`() {
		let result = generateWithContext(appFile("/App/A.swift", "import SwiftUI\nimport UIKit\nimport Observation\n"))
		expectOutput(result, contains: ["import Observation\n", "import SwiftUI\n", "import UIKit\n"])
	}
}
