import Testing
@testable import SwiftBeansGeneratorCore

@Suite("Generator — SPEC Generator rules → Application contexts and local packages")
struct GeneratorContextTests {
	@Test
	func `Given a local package with its own context When generated Then only the target context is a root`() {
		let result = generateWithContext(packageFile("Feature", "/Packages/Feature/Sources/Feature/Feature.swift", """
			@ApplicationContext
			public final class FeatureContext {}

			@Service
			public final class Search {
				public init() {}
			}
			"""))
		expectOutput(result, contains: ["extension AppContext {", "var search: Search {"])
		expectOutput(result, excludes: ["FeatureContext"])
	}

	@Test
	func `Given two contexts in the target When generated Then each gets an error`() {
		let result = SwiftBeansGeneration.generate(sources: [
			appContextFile,
			appFile("/App/OtherContext.swift", """
				@ApplicationContext
				final class OtherContext {}
				"""),
		])
		#expect(result.errorSummary == [
			"context.multiple /App/AppContext.swift:1:1",
			"context.multiple /App/OtherContext.swift:1:1",
		])
	}

	@Test
	func `Given a nested context When generated Then the extension uses its qualified name and the protocol its own name`() {
		let result = SwiftBeansGeneration.generate(sources: [
			appFile("/App/Root.swift", """
				enum App {
					@ApplicationContext
					final class Context {}
				}
				"""),
		])
		expectOutput(result, contains: [
			"protocol ContextProtocol: AnyObject {",
			"extension App.Context {",
			"extension App.Context: ContextProtocol {}",
		])
	}

	@Test
	func `Given a target without a context When generated Then an empty file is produced`() throws {
		let result = SwiftBeansGeneration.generate(sources: [
			appFile("/Feature/Search.swift", """
				@Service
				final class Search {
					init() {}
				}
				"""),
		])
		#expect(result.diagnostics.isEmpty, "\(result.renderedDiagnostics)")
		let output = try #require(result.output)
		#expect(output.hasPrefix("// Generated by SwiftBeans"))
		#expect(!output.contains("extension"))
		#expect(!output.contains("protocol"))
	}

	// MARK: - Local packages

	@Test
	func `Given a public bean in a local package that no app file imports When generated Then its module is imported`() {
		let result = generateWithContext(packageFile("Networking", "/Packages/Net/Sources/Networking/APIClient.swift", """
			import Foundation

			@Service
			public final class APIClient {
				public init() {}
			}
			"""))
		expectOutput(result, contains: ["import Networking\n", "var apiClient: APIClient {"])
	}

	@Test
	func `Given an open service in a local package When generated Then it is accepted`() {
		let result = generateWithContext(packageFile("Networking", "/Packages/Net/Sources/Networking/APIClient.swift", """
			@Service
			open class APIClient {
				public init() {}
			}
			"""))
		expectOutput(result, contains: ["var apiClient: APIClient {"])
	}

	@Test(arguments: [
		// Internal type, public initializer.
		("""
		@Service
		final class APIClient {
			public init() {}
		}
		""", 1, 1),
		// Public type, internal initializer.
		("""
		@Service
		public final class APIClient {
			init() {}
		}
		""", 1, 1),
		// Public struct relying on its (never public) implicit initializer.
		("""
		@Service
		public struct APIClient {}
		""", 1, 1),
		// Public bean in an internal configuration type.
		("""
		@Configuration
		enum Config {
			@Bean
			public static func client() -> APIClient { APIClient() }
		}
		""", 3, 2),
		// Internal bean in a public configuration type.
		("""
		@Configuration
		public enum Config {
			@Bean
			static func client() -> APIClient { APIClient() }
		}
		""", 3, 2),
	])
	func `Given a non-public provider in a local package When generated Then the build fails at it`(
		source: String,
		line: Int,
		column: Int
	) {
		let path = "/Packages/Net/Sources/Networking/APIClient.swift"
		let result = generateWithContext(packageFile("Networking", path, source))
		#expect(result.errorSummary == ["package.notPublic \(path):\(line):\(column)"])
		#expect(result.errors.first?.message.contains("public") == true)
	}

	@Test
	func `Given internal providers in the target When generated Then no public-ness is required`() {
		let result = generateWithContext(appFile("/App/APIClient.swift", """
			@Service
			final class APIClient {
				init() {}
			}
			"""))
		expectOutput(result, contains: ["var apiClient: APIClient {"])
	}
}
