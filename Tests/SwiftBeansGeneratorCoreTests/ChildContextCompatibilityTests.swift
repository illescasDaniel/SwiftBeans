import Foundation
import Testing

@testable import SwiftBeansGeneratorCore

@Suite("Child contexts — compatibility and resource constraints")
struct ChildContextCompatibilityTests {
	@Test func `Given many child graphs When generated Then each source is scanned once and parent emitted once`() {
		let parents = appFile("/App/Parent.swift", "@Service final class Shared {}")
		let children = appFile(
			"/App/Children.swift",
			(0..<12).map { "@ChildContext(of: AppContext.self) final class Child\($0) {}" }.joined(
				separator: "\n"))
		var scanned: [String] = []
		let result = SwiftBeansGeneration.generate(
			sources: [appContextFile, parents, children], onParse: { scanned.append($0.path) })
		#expect(result.errors.isEmpty)
		#expect(scanned.sorted() == [appContextFile.path, parents.path, children.path].sorted())
		#expect(
			occurrences(of: "var shared: Shared {", in: result.output!) == 2,
			"one protocol requirement and one getter, never copied to each child")
		#expect(occurrences(of: "protocol Child", in: result.output!) == 12)
	}

	@Test func `Given legacy root graph When generated Then Swift and graph artifacts remain byte identical`() {
		let result = generateWithContext(
			appFile(
				"/App/Legacy.swift",
				"""
				@Service final class A {}
				@Service(scope: .transient) final class B { init(a: A) {} }
				"""))
		let swift = """
			// Generated by SwiftBeans — do not edit.
			import Foundation
			import SwiftBeans

			protocol AppContextProtocol: AnyObject {
				var a: A { get }
				var b: B { get }
			}

			extension AppContext {
				var a: A {
					_swiftBeansRegistry.singleton(key: "a") {
						A()
					}
				}

				var b: B {
					B(a: self.a)
				}
			}

			extension AppContext: AppContextProtocol {}
			""" + "\n"
		let markdown = """
			# SwiftBeans graph

			- Context: `AppContext`
			- Providers: 2
			- Dependencies: 1

			## Providers

			| Key | Accessor | Scope | Provided by | Assisted |
			|-----|----------|-------|-------------|----------|
			| `A` | `a` | singleton | `A` | — |
			| `B` | `b` | transient | `B` | — |

			## Dependencies

			- `B` → `A`
			""" + "\n"
		let dot = """
			digraph SwiftBeans {
				rankdir=LR;
				node [shape=box, fontname="Helvetica"];
				"A" [label="A\\nsingleton · A"];
				"B" [label="B\\ntransient · B"];
				"B" -> "A";
			}
			""" + "\n"
		#expect(result.output == swift)
		#expect(result.graphMarkdown == markdown)
		#expect(result.graphDot == dot)
	}

	@Test func `Given invalid new child and previous artifacts When CLI fails Then old artifacts remain untouched`()
		throws
	{
		let folder = FileManager.default.temporaryDirectory.appending(
			path: "SwiftBeansPublication-\(UUID().uuidString)")
		try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
		defer { try? FileManager.default.removeItem(at: folder) }
		let source = folder.appending(path: "Client.swift")
		try "@ApplicationContext final class Root {}\n@ChildContext(of: Missing.self) final class Child {}"
			.write(to: source, atomically: true, encoding: .utf8)
		let outputs = ["Generated.swift", "Graph.md", "Graph.dot"].map { folder.appending(path: $0) }
		for output in outputs { try "previous".write(to: output, atomically: true, encoding: .utf8) }
		let repo = URL(filePath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
			.deletingLastPathComponent()
		let products =
			ProcessInfo.processInfo.environment["SWIFTBEANS_TEST_PRODUCTS"].map { URL(filePath: $0) }
			?? repo.appending(path: ".build/debug")
		let process = Process()
		process.executableURL = try #require(
			[
				products.appending(path: "SwiftBeansGenerator"),
				products.appending(path: "SwiftBeansGenerator-tool"),
				repo.appending(path: ".build/plugins/tools/debug/SwiftBeansGenerator-tool"),
			].first { FileManager.default.isExecutableFile(atPath: $0.path) },
			"the built generator executable must be available")
		process.arguments = [
			"--output", outputs[0].path, "--graph-markdown", outputs[1].path, "--graph-dot",
			outputs[2].path, source.path,
		]
		let pipe = Pipe()
		process.standardOutput = pipe
		process.standardError = pipe
		try process.run()
		_ = pipe.fileHandleForReading.readDataToEndOfFile()
		process.waitUntilExit()
		#expect(process.terminationStatus != 0)
		for output in outputs { #expect(try String(contentsOf: output, encoding: .utf8) == "previous") }
	}
}
