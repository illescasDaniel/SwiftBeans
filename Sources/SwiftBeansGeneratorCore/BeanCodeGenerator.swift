import SwiftBeans

/// Emits `SwiftBeansGenerated.swift` for a validated graph.
public enum BeanCodeGenerator {
	/// - Parameter additionalImports: Extra modules (e.g. `HTTIES`) required for foreign bean types
	///   under Swift’s member-import visibility. `Foundation` and `SwiftBeans` are always emitted.
	public static func generate(
		graph: BeanGraph,
		additionalImports: [String] = []
	) throws -> String {
		let sortedProviders = graph.providers.sorted(by: { $0.key.typeName < $1.key.typeName })
		var accessors: [String] = []
		var protocolRequirements: [String] = []
		for provider in sortedProviders {
			accessors.append(try generateAccessor(provider))
			protocolRequirements.append(generateProtocolRequirement(provider))
		}

		let body = accessors.joined(separator: "\n\n")
		let protocolBody = protocolRequirements.joined(separator: "\n")
		let protocolName = Naming.protocolName(forContextTypeName: graph.contextTypeName)
		let importLines = Self.importBlock(additionalImports: additionalImports)
		return """
			// Generated by SwiftBeans — do not edit.
			\(importLines)

			protocol \(protocolName): AnyObject {
			\(indent(protocolBody, level: 1))
			}

			extension \(graph.contextTypeName) {
			\(indent(body, level: 1))
			}

			extension \(graph.contextTypeName): \(protocolName) {}

			"""
	}

	private static func generateProtocolRequirement(_ provider: BeanProvider) -> String {
		let name = Naming.accessorName(forTypeName: provider.key.typeName)
		return "var \(name): \(provider.key.typeName) { get }"
	}

	private static func importBlock(additionalImports: [String]) -> String {
		var modules: [String] = ["Foundation", "SwiftBeans"]
		for module in additionalImports where !modules.contains(module) {
			modules.append(module)
		}
		return modules.map { "import \($0)" }.joined(separator: "\n")
	}

	private static func generateAccessor(_ provider: BeanProvider) throws -> String {
		guard let factory = provider.factory else {
			throw BeanGraphError.notImplemented("Missing factory metadata for \(provider.sourceName)")
		}
		let name = Naming.accessorName(forTypeName: provider.key.typeName)
		let construction = try constructionExpression(factory)
		let returnType = provider.key.typeName

		switch provider.scope {
		case .singleton:
			return """
				var \(name): \(returnType) {
					_swiftBeansRegistry.singleton(key: "\(provider.key.typeName)") {
						\(construction)
					}
				}
				"""
		case .transient:
			return """
				var \(name): \(returnType) {
					\(construction)
				}
				"""
		}
	}

	private static func constructionExpression(_ factory: BeanFactoryKind) throws -> String {
		switch factory {
		case .service(let typeName, let parameters):
			let args = argumentList(parameters)
			return "\(typeName)(\(args))"
		case .bean(let configurationType, let methodName, let parameters):
			let args = argumentList(parameters)
			return "\(configurationType).\(methodName)(\(args))"
		}
	}

	private static func argumentList(_ parameters: [BeanParameter]) -> String {
		parameters.map { parameter in
			let accessor = "self.\(Naming.accessorName(forTypeName: parameter.typeName))"
			if parameter.label == "_" {
				return accessor
			}
			return "\(parameter.label): \(accessor)"
		}.joined(separator: ", ")
	}

	private static func indent(_ text: String, level: Int) -> String {
		let prefix = String(repeating: "\t", count: level)
		return text
			.split(separator: "\n", omittingEmptySubsequences: false)
			.map { line in
				line.isEmpty ? String(line) : prefix + line
			}
			.joined(separator: "\n")
	}
}
