/// Emits `SwiftBeansGenerated.swift` for a validated graph.
enum CodeGenerator {
	static let header = "// Generated by SwiftBeans — do not edit."

	/// - Parameter context: `nil` when the target has no root context (header-only file).
	static func generate(context: ContextDecl?, providers: [BeanProvider], imports: [ImportRecord], plan: ContextCodePlan? = nil, includePreamble: Bool = true) -> String {
		guard let context else {
			return "\(header)\nimport Foundation\n"
		}

		// `any` follows the type, whatever qualifier it is spelled with.
		var anyTypes = Set<TypeKey>()
		for provider in plan?.beans ?? providers {
			if provider.spelledWithAny { anyTypes.insert(provider.key.type) }
			for parameter in provider.parameters where parameter.spelledWithAny {
				if let key = parameter.key { anyTypes.insert(key.type) }
			}
			for case let factory? in provider.parameters.map(\.factory) where factory.returnSpelledWithAny {
				anyTypes.insert(factory.returnKey)
			}
		}
		// Assisted keys are not injectable, so a defaulted parameter with one keeps its default.
		let visible = plan?.beans ?? providers
		let provided = Set(visible.filter { !$0.isAssisted }.map(\.key))
		func typeName(_ key: BeanKey) -> String {
			anyTypes.contains(key.type) ? "any \(key.type)" : key.type.description
		}

		// Factories resolve against the unqualified provider of the return type.
		var firstByType: [TypeKey: BeanProvider] = [:]
		for provider in visible where provider.key.qualifier == nil && firstByType[provider.key.type] == nil {
			firstByType[provider.key.type] = provider
		}

		let sorted = providers.sorted { $0.key.accessorName < $1.key.accessorName }
		/// `item: Item`, `page pageIndex: Int`, `_ query: String`
		func signature(_ provider: BeanProvider) -> String {
			provider.parameters.compactMap(\.assisted).map { argument in
				let name = switch argument.label {
				case nil: "_ \(argument.internalName)"
				case argument.internalName?: argument.internalName
				case let label?: "\(label) \(argument.internalName)"
				}
				return "\(name): \(argument.typeSpelling)"
			}.joined(separator: ", ")
		}
		let requirements = sorted.map { provider in
			if case .contextInput(let name) = provider.construction {
				return "\tvar \(name): \(plan?.typeSpelling(provider) ?? typeName(provider.key)) { get }"
			}
			return provider.isAssisted
				? "\tfunc \(provider.key.accessorName)(\(signature(provider))) -> \(typeName(provider.key))"
				: "\tvar \(provider.key.accessorName): \(typeName(provider.key)) { get }"
		}
		let injection = plan?.injection ?? ParameterInjection(sorted)
		let injectionProviders = plan?.beans ?? sorted
		func path(_ key: BeanKey) -> String { plan?.path(key) ?? "self.\(key.accessorName)" }
		let accessors = sorted.compactMap { provider -> String? in
			if case .contextInput = provider.construction { return nil }
			let index = injectionProviders.firstIndex { $0.key == provider.key }!

			let arguments = provider.parameters.compactMap { parameter -> String? in
				let value: String
				if let assisted = parameter.assisted {
					value = assisted.internalName
				} else if let factory = parameter.factory {
					switch plan?.bindings[parameter.location]?.factory ?? FactoryBinding.resolve(factory, providersByKey: { firstByType[$0] }) {
					case .deferred(let target), .assisted(let target):
						if let plan {
							let arguments = target.parameters.compactMap(\.assisted).enumerated().map { index, argument in
								argument.label.map { "\($0): argument\(index)" } ?? "argument\(index)"
							}.joined(separator: ", ")
							let call = path(target.key) + (target.isAssisted ? "(\(arguments))" : "")
							let names = target.parameters.compactMap(\.assisted).indices.map { "argument\($0)" }.joined(separator: ", ")
							let actor = plan.isMainActor ? " @MainActor" : ""
							let closureHead = (actor + (names.isEmpty ? "" : " " + names))
							let guardOpen = plan.isManaged ? "self._swiftBeansRegistry.requireOpen(); " : ""
							value = "{\(closureHead.isEmpty ? "" : closureHead + " in") \(guardOpen)return \(call) }"
						} else { value = FactoryBinding.closure(for: target) }
					case .missing, .mismatch:
						return nil
					}
				} else {
					switch plan == nil ? injection.injection(for: parameter, of: index) : plan!.bindings[parameter.location]?.injection {
					case .key(let key) where provided.contains(key):
						value = path(key)
					case .collection(let members):
						value = "[" + members.map { path(injectionProviders[$0].key) }.joined(separator: ", ") + "]"
					default:
						return nil
					}
				}
				return parameter.label.map { "\($0): \(value)" } ?? value
			}.joined(separator: ", ")
			let construction = switch provider.construction {
			case .initializer(let type): "\(type)(\(arguments))"
			case .contextInput(let name): "self.\(name)"
			case .staticMethod(let type, let name): "\(type).\(name)(\(arguments))"
			}
			if provider.isAssisted {
				let guardOpen = plan?.isManaged == true ? "\t\t_swiftBeansRegistry.requireOpen()\n\t\treturn " : "\t\t"
				return "\tfunc \(provider.key.accessorName)(\(signature(provider))) -> \(typeName(provider.key)) {\n\(guardOpen)\(construction)\n\t}"
			}
			let declaration = "\tvar \(provider.key.accessorName): \(typeName(provider.key)) {\n"
			switch provider.scope {
			case .singleton:
				return declaration + """
					\t\t_swiftBeansRegistry.singleton(key: "\(provider.key.registryKey)") {
					\t\t\t\(construction)
					\t\t}
					\t}
					"""
			case .transient:
				let guardOpen = plan?.isManaged == true ? "\t\t_swiftBeansRegistry.requireOpen()\n\t\treturn " : "\t\t"
				return declaration + guardOpen + "\(construction)\n\t}"
			}
		}

		let protocolName = "\(context.simpleName)Protocol"
		var output = includePreamble ? "\(header)\n\(importBlock(imports))\n" : ""
		if plan?.isMainActor == true { output += "@MainActor\n" }
		output += "protocol \(protocolName): AnyObject {\n"
		output += requirements.map { "\($0)\n" }.joined()
		if plan?.isManaged == true { output += "\tfunc close() async\n" }
		output += "}\n\n"
		output += "extension \(context.name) {\n"
		output += accessors.joined(separator: "\n\n")
		output += accessors.isEmpty ? "" : "\n"
		output += "}\n\n"
		output += "extension \(context.name): \(protocolName) {}\n"
		return output
	}

	/// `Foundation`, `SwiftBeans`, sorted unconditional imports, then one `#if` block per condition.
	static func importBlock(_ records: [ImportRecord]) -> String {
		struct Flags { var testable = false; var preconcurrency = false }
		let fixed: Set<String> = ["Foundation", "SwiftBeans", "Swift"]
		var unconditional: [String: Flags] = [:]
		var conditional: [String: [String: Flags]] = [:]
		for record in records where !fixed.contains(record.module) {
			if let condition = record.condition {
				var flags = conditional[condition, default: [:]][record.module] ?? Flags()
				flags.testable = flags.testable || record.testable
				flags.preconcurrency = flags.preconcurrency || record.preconcurrency
				conditional[condition, default: [:]][record.module] = flags
			} else {
				var flags = unconditional[record.module] ?? Flags()
				flags.testable = flags.testable || record.testable
				flags.preconcurrency = flags.preconcurrency || record.preconcurrency
				unconditional[record.module] = flags
			}
		}
		func line(_ module: String, _ flags: Flags) -> String {
			(flags.preconcurrency ? "@preconcurrency " : "") + (flags.testable ? "@testable " : "") + "import \(module)\n"
		}

		var block = "import Foundation\nimport SwiftBeans\n"
		for module in unconditional.keys.sorted() {
			block += line(module, unconditional[module]!)
		}
		for condition in conditional.keys.sorted() {
			let modules = conditional[condition]!.keys.filter { unconditional[$0] == nil }.sorted()
			guard !modules.isEmpty else { continue }
			block += "#if \(condition)\n"
			for module in modules {
				block += line(module, conditional[condition]![module]!)
			}
			block += "#endif\n"
		}
		return block
	}
}
